/**
 * @brief Verify all 32 bits of a uint32_t can be used.
 */
TEST_F(UsageBitmapTest, AllBitsInWord)
{
    const uint32_t base_index = 0;

    /*
     * Set every bit in the first word.
     */
    for (uint32_t bit = 0;
         bit < BITS_PER_ELEMENT;
         bit++)
    {
        ASSERT_TRUE(
            update_usage_bit(
                storage,
                base_index + bit,
                true
            )
        );
    }

    /*
     * Every bit should now be set.
     */
    for (uint32_t bit = 0;
         bit < BITS_PER_ELEMENT;
         bit++)
    {
        EXPECT_TRUE(
            check_usage_bit(
                base_index + bit
            )
        );
    }

    /*
     * Read the sector back.
     */
    uint8_t result[SECTOR_SIZE]{};

    ASSERT_TRUE(
        storage->read_block(
            storage->context,
            USAGE_BITMAP_START_SECTOR,
            result
        )
    );

    uint32_t word = 0;

    memcpy(
        &word,
        result,
        sizeof(uint32_t)
    );

    EXPECT_EQ(
        word,
        0xFFFFFFFFu
    );
}


/**
 * @brief Verify bitmap sector boundary at sector 4096.
 *
 * One 512-byte bitmap sector contains:
 *
 *   512 * 8 = 4096 bits
 *
 * Therefore:
 *
 *   data sector 4095 -> bitmap sector 0
 *   data sector 4096 -> bitmap sector 1
 */
TEST_F(UsageBitmapTest, BitmapSectorBoundary)
{
    const uint32_t first_sector_index = 0;
    const uint32_t last_index_sector_0 = 4095;
    const uint32_t first_index_sector_1 = 4096;

    /*
     * Set the final bit represented by bitmap sector 0.
     */
    ASSERT_TRUE( update_usage_bit( storage, last_index_sector_0, true));

    EXPECT_TRUE( check_usage_bit( last_index_sector_0));

    /*
     * Set the first bit represented by bitmap sector 1.
     */
    ASSERT_TRUE( update_usage_bit( storage, first_index_sector_1, true));

    EXPECT_TRUE( check_usage_bit( first_index_sector_1));

    /*
     * Make sure the two bits didn't interfere with each other.
     */
    EXPECT_TRUE( check_usage_bit( last_index_sector_0));

    EXPECT_TRUE( check_usage_bit( first_index_sector_1));

    /*
     * Read bitmap sector 0.
     */
    uint8_t sector0[SECTOR_SIZE]{};

    ASSERT_TRUE( storage->read_block( storage->context, USAGE_BITMAP_START_SECTOR, sector0));

    /*
     * Bit 4095 is:
     *
     * word = 127
     * bit  = 31
     */
    uint32_t word0 = 0;

    memcpy( &word0, &sector0[127 * sizeof(uint32_t)], sizeof(uint32_t));

    EXPECT_EQ( word0, 0x80000000u);


    /*
     * Read bitmap sector 1.
     */
    uint8_t sector1[SECTOR_SIZE]{};

    ASSERT_TRUE( storage->read_block( storage->context, USAGE_BITMAP_START_SECTOR + 1, sector1));

    /*
     * Bit 4096 is:
     *
     * word = 0
     * bit  = 0
     */
    uint32_t word1 = 0;

    memcpy( &word1, sector1, sizeof(uint32_t));

    EXPECT_EQ( word1, 0x00000001u);
}


/**
 * @brief Verify the beginning and end of every bitmap sector.
 */
TEST_F(UsageBitmapTest, EveryBitmapSectorBoundary)
{
    const uint32_t sectors_per_bitmap_sector =
        SECTOR_SIZE * 8;

    for (uint32_t bitmap_sector = 0;
         bitmap_sector < USAGE_BITMAP_SECTOR_SIZE;
         bitmap_sector++)
    {
        uint32_t first_index =
            bitmap_sector *
            sectors_per_bitmap_sector;

        /*
         * Don't go beyond the logical bitmap.
         */
        if (first_index >= TOTAL_DATA_SECTOR_SIZE)
        {
            break;
        }

        uint32_t last_index =
            first_index +
            sectors_per_bitmap_sector -
            1;

        if (last_index >= TOTAL_DATA_SECTOR_SIZE)
        {
            last_index =
                TOTAL_DATA_SECTOR_SIZE - 1;
        }

        /*
         * Set first bit in this bitmap sector.
         */
        ASSERT_TRUE(
            update_usage_bit(
                storage,
                first_index,
                true
            )
        );

        EXPECT_TRUE(
            check_usage_bit(first_index)
        );

        /*
         * Set final bit in this bitmap sector.
         */
        ASSERT_TRUE(
            update_usage_bit(
                storage,
                last_index,
                true
            )
        );

        EXPECT_TRUE(
            check_usage_bit(last_index)
        );

        /*
         * Check that the expected bitmap sector
         * contains the modifications.
         */
        uint8_t result[SECTOR_SIZE]{};

        ASSERT_TRUE(
            storage->read_block(
                storage->context,
                USAGE_BITMAP_START_SECTOR +
                    bitmap_sector,
                result
            )
        );

        /*
         * First bit.
         */
        uint32_t first_word = 0;

        memcpy(
            &first_word,
            result,
            sizeof(uint32_t)
        );

        EXPECT_NE(
            first_word & 0x1u,
            0u
        );

        /*
         * Last bit.
         */
        uint32_t last_word = 0;

        memcpy(
            &last_word,
            &result[127 * sizeof(uint32_t)],
            sizeof(uint32_t)
        );

        /*
         * If this is a complete bitmap sector,
         * the last bit should be bit 31.
         */
        if (last_index - first_index == 4095)
        {
            EXPECT_NE(
                last_word & 0x80000000u,
                0u
            );
        }
    }
}


/**
 * @brief Verify changing one bit does not modify neighbouring bits.
 */
TEST_F(UsageBitmapTest, DoesNotModifyNeighbouringBits)
{
    const uint32_t index = 100;

    /*
     * Set the target bit.
     */
    ASSERT_TRUE(
        update_usage_bit(
            storage,
            index,
            true
        )
    );

    EXPECT_TRUE(
        check_usage_bit(index)
    );

    /*
     * Neighbouring bits should remain clear.
     */
    EXPECT_FALSE(
        check_usage_bit(index - 1)
    );

    EXPECT_FALSE(
        check_usage_bit(index + 1)
    );

    /*
     * Also check the beginning/end of the word.
     */
    EXPECT_FALSE(
        check_usage_bit(96)
    );

    EXPECT_FALSE(
        check_usage_bit(127)
    );
}


