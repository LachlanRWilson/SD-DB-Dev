class UsageBitmapTest : public ::testing::Test
{
protected:

    Storage *storage = &heap_storage;
    HeapStorageContext storage_ctx;

    uint8_t *storage_mem = nullptr;

    /*
     * Storage layout:
     *
     *   Sector 0 ... Superheader
     *   Sector 1 ... Usage bitmap
     *   Sector N ... Data
     *
     * The bitmap itself is rounded up to whole sectors.
     */
    static constexpr uint16_t STORAGE_SECTOR_COUNT =
        SUPERHEADER_SECTOR_SIZE +
        USAGE_BITMAP_SECTOR_SIZE +
        TOTAL_DATA_SECTOR_SIZE;


    void SetUp() override
    {
        /*
         * These should match the values generated by your
         * current implementation.
         */
//         ASSERT_EQ(SUPERHEADER_SECTOR_SIZE, 1);
//         ASSERT_EQ(USAGE_BITMAP_SECTOR_SIZE, 61);
//         ASSERT_EQ(TOTAL_DATA_SECTOR_SIZE, 30969);

        /*
         * Allocate the simulated SD card.
         */
        storage_mem =
            new uint8_t[
                SECTOR_SIZE * STORAGE_SECTOR_COUNT
            ];

        ASSERT_NE(storage_mem, nullptr);

        /*
         * Start with an erased/empty SD card.
         */
        memset(
            storage_mem,
            0,
            SECTOR_SIZE * STORAGE_SECTOR_COUNT
        );

        /*
         * Initialise heap storage.
         */
        ASSERT_TRUE(
            HeapStorage_Init(
                &storage_ctx,
                storage_mem,
                SECTOR_SIZE,
                STORAGE_SECTOR_COUNT
            )
        );

        storage->context = &storage_ctx;

        /*
         * Clear the global bitmap before each test.
         */
        memset(
            usage_bitmap,
            0,
            USAGE_BITMAP_STORAGE_SIZE *
                sizeof(uint32_t)
        );
    }


    void TearDown() override
    {
        delete[] storage_mem;
        storage_mem = nullptr;
    }


    /**
     * @brief Read a complete bitmap sector from the
     *        simulated SD card.
     */
    void read_bitmap_sector(
        uint32_t bitmap_sector,
        uint8_t *buffer)
    {
        ASSERT_NE(buffer, nullptr);

        ASSERT_TRUE(
            storage->read_block(
                storage->context,
                USAGE_BITMAP_START_SECTOR +
                    bitmap_sector,
                buffer
            )
        );
    }


    /**
     * @brief Verify a bitmap sector is completely zero.
     */
    void expect_sector_zero(
        uint32_t bitmap_sector)
    {
        uint8_t buffer[SECTOR_SIZE]{};

        read_bitmap_sector(
            bitmap_sector,
            buffer
        );

        for (uint32_t i = 0; i < SECTOR_SIZE; i++)
        {
            EXPECT_EQ(
                buffer[i],
                0
            );
        }
    }
};


/**
 * @brief Verify the bitmap can be read from the SD card.
 */
TEST_F(UsageBitmapTest, ReadUsageBitmap)
{
    /*
     * Put a known pattern into every bitmap sector
     * on the simulated SD card.
     */
    uint8_t pattern[SECTOR_SIZE];

    memset(
        pattern,
        0xAA,
        sizeof(pattern)
    );

    for (uint32_t sector = 0;
         sector < USAGE_BITMAP_SECTOR_SIZE;
         sector++)
    {
        ASSERT_TRUE(
            storage->write_block(
                storage->context,
                USAGE_BITMAP_START_SECTOR + sector,
                pattern
            )
        );
    }

    /*
     * Read the complete bitmap.
     */
    ASSERT_TRUE(
        read_usage_bitmap(
            storage
        )
    );

    /*
     * Every uint32_t should now contain 0xAAAAAAAA.
     */
    for (uint32_t i = 0;
         i < USAGE_BITMAP_STORAGE_SIZE;
         i++)
    {
        EXPECT_EQ(
            usage_bitmap[i],
            0xAAAAAAAAu
        );
    }
}


